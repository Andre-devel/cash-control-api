package com.cashcontrol.api.service;

import com.cashcontrol.api.domain.entity.Account;
import com.cashcontrol.api.domain.entity.CreditCard;
import com.cashcontrol.api.domain.entity.Invoice;
import com.cashcontrol.api.domain.entity.Transaction;
import com.cashcontrol.api.dto.request.CreateCardRequest;
import com.cashcontrol.api.dto.request.EditCardRequest;
import com.cashcontrol.api.dto.request.PayInvoiceRequest;
import com.cashcontrol.api.dto.request.RecordChargeRequest;
import com.cashcontrol.api.dto.response.CreditCardResponse;
import com.cashcontrol.api.dto.response.InvoiceItemResponse;
import com.cashcontrol.api.dto.response.InvoiceResponse;
import com.cashcontrol.api.dto.response.LimitUsageResponse;
import com.cashcontrol.api.dto.response.SpendingByCategoryResponse;
import com.cashcontrol.api.service.InvoiceCycleCalculator.InvoiceCycleInfo;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.List;
import java.util.UUID;

public interface CreditCardService {

    CreditCardResponse createCard(CreateCardRequest request, UUID userId);

    List<CreditCardResponse> listCards(UUID userId);

    CreditCardResponse getCard(UUID id, UUID userId);

    CreditCardResponse editCard(UUID id, EditCardRequest request, UUID userId);

    CreditCardResponse archiveCard(UUID id, UUID userId);

    CreditCardResponse unarchiveCard(UUID id, UUID userId);

    InvoiceItemResponse recordCharge(UUID cardId, RecordChargeRequest request, UUID userId);

    InvoiceResponse getInvoice(UUID cardId, String referenceMonth, UUID userId, int page, int size);

    InvoiceResponse payInvoice(UUID invoiceId, PayInvoiceRequest request, UUID userId);

    /**
     * Grava o pagamento já validado (fatura e conta do usuário, valor que cabe no restante)
     * e aplica à fatura. Sobre fatura quitada por "marcar como paga" só liga o pagamento a
     * ela, sem mexer no pago. Devolve a transação gravada.
     */
    Transaction recordInvoicePayment(Invoice invoice, Account sourceAccount, BigDecimal amount, LocalDate paymentDate);

    LimitUsageResponse getLimitUsage(UUID cardId, UUID userId);

    List<SpendingByCategoryResponse> getSpendingByCategory(UUID cardId, LocalDate from, LocalDate to, UUID userId);

    /**
     * A fatura do ciclo, criando-a ABERTA e zerada se ainda não existir.
     *
     * <p>Público porque a importação de fatura em PDF precisa exatamente disto: o PDF
     * de julho pode chegar antes de qualquer lançamento do mês ter sido registrado, e
     * duplicar aqui a regra de "acha a fatura do mês ou abre uma" daria duas versões
     * da mesma decisão.
     */
    Invoice getOrCreateInvoice(CreditCard card, InvoiceCycleInfo cycleInfo);

    void createInvoiceItemForTransaction(Transaction tx);

    void syncInvoiceItemForTransaction(Transaction tx);

    void detachInvoiceItemForTransaction(UUID transactionId);

    /**
     * Removes every invoice item generated by an installment series and gives the
     * corresponding amounts back to their invoices.
     *
     * @throws com.cashcontrol.api.domain.exception.BusinessRuleException if any item
     *         sits on an invoice that is no longer OPEN — a closed invoice reflects
     *         what the issuer already charged and must not be rewritten.
     */
    void deleteInvoiceItemsForInstallmentSeries(UUID installmentSeriesId);

    /**
     * Soma {@code delta} ao total da fatura ({@code Invoice.addToTotal}) e leva a mudança ao
     * saldo rotativo que ela empurra para a seguinte. Todo ajuste de total passa por aqui.
     */
    void adjustInvoiceTotal(Invoice invoice, BigDecimal delta);

    /**
     * Alinha o item rotativo que a fatura deixou na seguinte com o que ela ainda deve
     * ({@code Invoice.revolvingBalance}): cria, ajusta ou cancela o item, e o ajuste do total da
     * seguinte segue em cascata se ela também estiver PARCIAL.
     */
    void syncRevolvingItem(Invoice invoice);

    /**
     * Devolve à fatura um pagamento que foi excluído: tira o valor do pago, refaz o status e o
     * rotativo, e reabre as compras se a fatura deixou de estar paga.
     */
    void revertInvoicePayment(UUID invoiceId, BigDecimal amount);

    /**
     * Alinha o status das compras da fatura com o que foi pago: PAGAS quando a fatura está
     * quitada, PENDENTES caso contrário. Uma fatura PARCIAL conta como quitada quando a fatura
     * que recebeu o rotativo dela está quitada — o restante foi pago por lá. Por isso a regra
     * também desce para as faturas cujo rotativo está nesta.
     */
    void syncInvoicePurchases(Invoice invoice, LocalDate paymentDate);
}
